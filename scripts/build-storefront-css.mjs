#!/usr/bin/env node
// scripts/build-storefront-css.mjs
//
// Builds extensions/rewards-widget/assets/rewards-theme.css from the client's prototype
// (docs/reference/Ecofynd Rewards V1 (1).html): its design tokens and the storefront rules the widget and the
// Rewards page use, copied unchanged except that every selector is prefixed with ".ecr " so nothing leaks into
// (or is overridden by) the merchant's theme. Light theme only. Re-run after changing the list below.
//
//   node scripts/build-storefront-css.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'docs/reference/Ecofynd Rewards V1 (1).html');
const OUT = join(ROOT, 'extensions/rewards-widget/assets/rewards-theme.css');

// Rules whose FIRST selector starts with one of these are kept.
const KEEP = [
  '.num', '.mono', '.muted', '.faint', '.link', '.sr', '.btn', '.pill', '.st-', '.eyebrow', '.card', '.row-between', '.sec-h',
  '.rw-title', '.bal', '.owed', '.pend', '.goal', '.bar', '.rlist', '.ritem', '.earn', '.zero', '.ladder', '.choice', '.tl',
  '.plus', '.minus', '.ok', '.err', '.warnbox', '.wbtn', '.wpanel',
];

const lines = readFileSync(SRC, 'utf8').split('\n');
const css = lines.slice(7, 316); // the first <style> block of the prototype
const tokens = css.slice(css.findIndex((l) => l.startsWith(':root{'))).join('\n').match(/^:root\{([\s\S]*?)\n\}/m)[1];

const kept = [];
for (const line of css) {
  const m = /^(\.[^{]+)\{(.*)\}\s*$/.exec(line.trim());
  if (!m) continue;
  const selectors = m[1].split(',').map((s) => s.trim());
  if (!KEEP.some((k) => selectors[0].startsWith(k))) continue;
  kept.push(`${selectors.map((s) => `.ecr ${s}`).join(',')}{${m[2]}}`);
}

const header = `/* Reward Points storefront styles (widget and Rewards page).
   GENERATED by scripts/build-storefront-css.mjs from the client's prototype: tokens and rules copied unchanged,
   every selector scoped under .ecr. Do not edit by hand. */
`;
const base = `
.ecr{${tokens.trim()}
  box-sizing:border-box;font-family:var(--f-body);font-size:15px;line-height:1.5;color:var(--ink);-webkit-font-smoothing:antialiased}
.ecr *,.ecr *::before,.ecr *::after{box-sizing:border-box}
.ecr h1,.ecr h2,.ecr h3,.ecr h4,.ecr p{margin:0}
.ecr button{font:inherit;color:inherit}
.ecr [hidden]{display:none!important}
.ecr a{color:var(--umber)}
.ecr .btn{text-decoration:none}
`;
// Layout that belongs to this build, not to the prototype's phone frame.
const layout = `
/* ===== layout for the real storefront (not in the prototype) ===== */
.ecr-page{max-width:560px;margin:32px auto 80px;padding:0 16px;display:grid;gap:18px}
.ecr-widget{position:fixed;bottom:20px;z-index:2147483000}
.ecr-widget.side-right{right:16px}.ecr-widget.side-left{left:16px}
.ecr-widget .wpanel{bottom:56px}
.ecr-widget.side-right .wpanel{right:0}.ecr-widget.side-left .wpanel{left:0;right:auto}
.ecr .wbtn svg,.ecr .tl-ic svg,.ecr .earn .e svg,.ecr .pend-top svg,.ecr .earnline svg{display:block}
.ecr .wbig{font-family:var(--f-display);font-weight:600;font-size:32px;line-height:1}
.ecr .rbtn{margin-left:auto}
.ecr .codebox{display:flex;align-items:center;justify-content:space-between;gap:10px;flex-wrap:wrap}
.ecr .toastline{min-height:0}
.ecr .center{text-align:center}
.ecr .grid{display:grid;gap:10px}
.ecr .wpanel .bar{margin-top:2px}
.ecr .wbtn{position:relative}
.ecr .wbtn .dot{position:absolute;top:5px;right:7px;width:10px;height:10px;border-radius:50%;background:var(--gold);box-shadow:0 0 0 2px var(--umber)}
.ecr .notes{display:grid;gap:6px}
`;
writeFileSync(OUT, header + base + kept.join('\n') + '\n' + layout);
console.log(`wrote ${OUT}: ${kept.length} rules`);
